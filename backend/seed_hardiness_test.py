def seed():
    db = SessionLocal()
    try:
        existing = db.query(Test).filter(Test.slug == "hardiness-maddi").first()
        if existing:
            print(f"Тест уже существует (id={existing.id}). Удаляю и пересоздаю...")
            db.delete(existing)
            db.commit()

        test = Test(
            slug="hardiness-maddi",
            title="Тест жизнестойкости (Hardiness Survey)",
            description=(
                "Тест жизнестойкости Мадди — адаптация опросника Hardiness Survey. "
                "Оценивает способность личности выдерживать стрессовую ситуацию, "
                "сохраняя внутреннюю сбалансированность. "
                "Три субшкалы: Вовлечённость, Контроль, Принятие риска."
            ),
            duration_minutes=15,
            questions_count=len(QUESTIONS),
            is_active=True,
        )
        db.add(test)
        db.flush()  # get test.id

        for pos, text in QUESTIONS:
            q = TestQuestion(
                test_id=test.id,
                position=pos,
                text=text,
                is_reverse=(pos in ALL_REVERSE),
                subscale=get_subscale(pos),
            )
            db.add(q)

        db.commit()
        print(f"✅ Тест жизнестойкости создан (id={test.id}) с {len(QUESTIONS)} вопросами.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
