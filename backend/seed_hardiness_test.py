# Subscale: involvement (Вовлечённость)
#   Direct:  4, 12, 22, 23, 24, 29, 41
#   Reverse: 2, 3, 10, 11, 14, 28, 32, 37, 38, 40, 42
# Subscale: control (Контроль)
#   Direct:  9, 15, 17, 21, 25, 44
#   Reverse: 1, 5, 6, 8, 16, 20, 27, 31, 35, 39, 43
# Subscale: risk_taking (Принятие риска)
#   Direct:  34, 45
#   Reverse: 7, 13, 18, 19, 26, 30, 33, 36

INVOLVEMENT_DIRECT  = {4, 12, 22, 23, 24, 29, 41}
INVOLVEMENT_REVERSE = {2, 3, 10, 11, 14, 28, 32, 37, 38, 40, 42}
CONTROL_DIRECT      = {9, 15, 17, 21, 25, 44}
CONTROL_REVERSE     = {1, 5, 6, 8, 16, 20, 27, 31, 35, 39, 43}
RISK_DIRECT         = {34, 45}
RISK_REVERSE        = {7, 13, 18, 19, 26, 30, 33, 36}

ALL_REVERSE = INVOLVEMENT_REVERSE | CONTROL_REVERSE | RISK_REVERSE

def get_subscale(pos: int) -> str:
    if pos in INVOLVEMENT_DIRECT or pos in INVOLVEMENT_REVERSE:
        return "involvement"
    if pos in CONTROL_DIRECT or pos in CONTROL_REVERSE:
        return "control"
    if pos in RISK_DIRECT or pos in RISK_REVERSE:
        return "risk_taking"
    return ""

